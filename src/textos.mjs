let idioma = 'en';

export function ponerIdioma(i) {
  idioma = TEXTOS[i] ? i : 'en';
}

export function t(clave, datos = {}) {
  const s = TEXTOS[idioma][clave] ?? TEXTOS.en[clave] ?? clave;
  return s.replace(/\{(\w+)\}/g, (_, k) => (datos[k] ?? `{${k}}`));
}
